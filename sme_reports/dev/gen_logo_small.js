// Regenerates render/assets/logo_small.js: the Avante logo downscaled for
// the System Activity pages (incident/system_page.js). The source,
// render/assets/logo.js, is 9779x2500 px (422 KB of base64) and every page
// embeds its logo, so on a 108-page fleet run the logo alone was ~26 MB of
// the zipped pages. The page shows it 46 px tall (36 px on phones); this
// renders it at 2x that (92 px) for high-density screens, ~15 KB.
// Resampled in Chromium's canvas (high-quality smoothing, alpha kept).
// Usage: node sme_reports/dev/gen_logo_small.js
const fs = require("fs");
const path = require("path");
const puppeteer = require("puppeteer");

const HEIGHT = 92;
const source = require("../render/assets/logo");

(async () => {
  const browser = await puppeteer.launch({
    headless: "new",
    executablePath: process.env.PUPPETEER_EXECUTABLE_PATH || undefined,
    args: ["--no-sandbox", "--disable-setuid-sandbox"]
  });
  try {
    const page = await browser.newPage();
    const out = await page.evaluate(async (src, h) => {
      const img = new Image();
      img.src = `data:image/png;base64,${src}`;
      await img.decode();
      // Halve in steps until within 2x of the target, then one final draw:
      // a single 27x downscale aliases thin strokes even with smoothing.
      let cur = img;
      let w = img.width;
      let ch = img.height;
      while (ch / 2 >= h * 2) {
        const c = document.createElement("canvas");
        c.width = Math.round(w / 2);
        c.height = Math.round(ch / 2);
        const g = c.getContext("2d");
        g.imageSmoothingQuality = "high";
        g.drawImage(cur, 0, 0, c.width, c.height);
        cur = c;
        w = c.width;
        ch = c.height;
      }
      const c = document.createElement("canvas");
      c.height = h;
      c.width = Math.round((img.width * h) / img.height);
      const g = c.getContext("2d");
      g.imageSmoothingQuality = "high";
      g.drawImage(cur, 0, 0, c.width, c.height);
      return { w: c.width, h: c.height, b64: c.toDataURL("image/png").split(",")[1] };
    }, source, HEIGHT);
    const file = path.join(__dirname, "..", "render", "assets", "logo_small.js");
    fs.writeFileSync(
      file,
      `// GENERATED by dev/gen_logo_small.js — do not edit by hand.\n` +
        `// Avante logo, ${out.w}x${out.h} PNG (base64), downscaled from logo.js for the\n` +
        `// System Activity pages.\n` +
        `module.exports =\n  "${out.b64}";\n`
    );
    console.log(`wrote ${path.relative(process.cwd(), file)}: ${out.w}x${out.h}, ${out.b64.length} base64 chars`);
  } finally {
    await browser.close();
  }
})().catch((e) => {
  console.error(e.stack || e.message);
  process.exit(1);
});
